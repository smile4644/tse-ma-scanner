"""Publish an accepted buy scan without rebasing generated JSON/CSV artifacts.

GitHub Actions jobs can run from older checkouts while another scan or a short
scan publishes to main. A normal git pull --rebase cannot merge large
machine-generated files and may turn a successful scan into a failed workflow.

This publisher saves an immutable local snapshot, re-bases *the publication*
(not the generated commit) on the current remote tip, and retries raced pushes.
An older result is never allowed to replace newer official scan JSON.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import tempfile


def git(*args: str, check: bool = True) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(["git", *args], check=check, capture_output=True)


def version(info: dict) -> tuple[str, str]:
    return (str(info.get("target_date") or ""), str(info.get("generated_at_jst") or ""))


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def permitted_path(name: str) -> bool:
    p = PurePosixPath(name)
    return (not p.is_absolute() and ".." not in p.parts and
            (name == "data/universe_top1000.csv" or name.startswith("results/")))


def remote_version(session: str, date: str) -> tuple[str, str]:
    paths = [
        Path("results") / f"latest_{session}.json",
        Path("results/archive") / f"{date}_{session}.json",
    ]
    versions = []
    for p in paths:
        if not p.exists():
            continue
        try:
            entry = load_json(p)
        except (OSError, ValueError) as exc:
            raise RuntimeError(f"Refusing to publish over malformed remote JSON: {p}") from exc
        versions.append(version(entry))
    return max(versions, default=("", ""))


def publish(session: str, attempts: int = 5) -> str:
    if session not in {"noon", "close"}:
        raise ValueError("session must be noon or close")
    latest = Path("results") / f"latest_{session}.json"
    candidate = load_json(latest)
    if (candidate.get("session") != session or not candidate.get("target_date") or
            not candidate.get("generated_at_jst") or candidate.get("write_status") != "accepted" or
            candidate.get("safety_gate_errors")):
        raise RuntimeError("Refusing to publish unverified or failed buy result")
    date, generated = version(candidate)
    print(f"[publish] candidate {date}/{session} generated={generated}", flush=True)

    # Stage once before updating the checkout, and keep candidate bytes off-tree.
    git("add", "--", "data/universe_top1000.csv", "results/")
    names_raw = git("diff", "--cached", "--name-only", "-z").stdout
    names = [p.decode("utf-8") for p in names_raw.split(b"\0") if p]
    if not names:
        print("[publish] no local changes", flush=True)
        return "unchanged"
    if not all(permitted_path(p) for p in names):
        raise RuntimeError("Unapproved file in buy publication")

    with tempfile.TemporaryDirectory(prefix="tse-publish-") as scratch:
        saved = Path(scratch)
        for name in names:
            src = Path(name)
            if src.is_file():
                dst = saved / name
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(src, dst)
            elif src.exists():
                raise RuntimeError(f"Unexpected publication path type: {name}")

        for number in range(1, attempts + 1):
            git("fetch", "origin", "main")
            # Safe on an ephemeral GitHub Actions checkout: generated bytes
            # have been snapshotted outside the repository above.
            git("reset", "--hard", "origin/main")
            present = remote_version(session, date)
            if present >= (date, generated):
                print(f"[publish] newer/equal official result already present: {present}", flush=True)
                return "superseded"
            for name in names:
                dst = Path(name)
                src = saved / name
                if src.is_file():
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(src, dst)
                    git("add", "--", name)
                else:
                    git("rm", "-f", "--ignore-unmatch", "--", name)
            if git("diff", "--cached", "--quiet", check=False).returncode == 0:
                print("[publish] current remote already contains candidate files", flush=True)
                return "unchanged"
            git("commit", "-m", f"Update TSE MA results ({session})")
            pushed = git("push", "origin", "HEAD:main", check=False)
            if pushed.returncode == 0:
                print(f"[publish] saved accepted {date}/{session} on attempt {number}", flush=True)
                return "saved"
            print(f"[publish] push race, retry {number}/{attempts}", flush=True)
        raise RuntimeError(f"Failed to publish after {attempts} fetch/reset/retry attempts")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--session", required=True, choices=["noon", "close"])
    args = parser.parse_args()
    publish(args.session)


if __name__ == "__main__":
    main()
